import type { ReactNode } from "react";

/**
 * **설명 글 한 덩이를 통째로 번역하기.**
 *
 * ── 왜 필요한가 ──────────────────────────────────────────────────────────
 * 이 앱의 설명 글은 문장 가운데를 굵게 씁니다 — 「한 칸을 다 찍고 **「이 칸 다 찍었습니다」**를
 * 누르면 그 칸 기록이 **찍은 것으로 통째로 바뀝니다**」 처럼요. 그런데 b 요소를 쓰면 그 한
 * 문장이 화면에서 **텍스트 토막 다섯 개**로 쪼개집니다. 사전은 토막을 찾지 못하고, 영문으로
 * 바꿀 때 「한 칸을 다 찍고」만 한국어로 남습니다.
 *
 * 토막마다 번역을 붙이는 길도 있지만 그러면 **어순이 깨집니다.** 한국어는 서술어가 끝에,
 * 영어는 앞에 옵니다 — 토막을 제자리에 그대로 두고 단어만 바꾸면 영어가 아니라 영어 단어의
 * 줄이 됩니다. 인증 방문 때 내보이는 화면입니다.
 *
 * 그래서 **글귀 하나를 열쇠 하나로** 둡니다. 굵게는 `**이렇게**` 적고, 이 함수가 번역을 끝낸
 * 글귀에서 그 표시를 찾아 굵게로 돌려놓습니다. 두 말이 서로 다른 자리를 굵게 할 수도
 * 있습니다 - 영어에서 강조할 말이 한국어와 같은 자리에 있을 이유가 없습니다.
 *
 * 쓰는 법 — 화면 쪽:
 *   {rich(t("한 칸을 다 찍고 **「이 칸 다 찍었습니다」**를 누르면 ..."))}
 * 서버 화면:
 *   const t = await getT();
 *   {rich(t("...", { n: 3 }))}
 *
 * 굵은 부분에 색·크기를 주려면 둘째 값으로 클래스를 넘깁니다 — 숫자를 크게 보여 주던 자리를
 * 한 글귀로 합칠 때 쓰입니다: rich(t("... **{n}권** ..."), "text-lg text-gia-navy").
 */
export function rich(text: string, boldClass?: string): ReactNode {
  const parts = text.split("**");
  // 표시가 없으면 그대로 - 쓸데없이 조각을 만들지 않습니다.
  if (parts.length === 1) return text;
  return parts.map((part, i) =>
    // 글귀는 그려지는 동안 바뀌지 않으므로 자리를 열쇠로 써도 안전합니다.
    i % 2 === 1 ? (
      <b key={i} className={boldClass}>
        {part}
      </b>
    ) : (
      <span key={i}>{part}</span>
    )
  );
}
